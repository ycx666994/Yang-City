/* 杨城总图 · 全城层的基础设施
   17 个片区各自成篇（见 yc-district-plan.js），这一层只放「城」而不是「区」的东西：
   澄川河、三座跨江桥、贯穿北岸的城际高架、以及片区之间那几条干道。
   3D 全城（map.html）与平面总图（index.html）共用同一份数据，两边的城要长得一样。 */
(function (global) {
  "use strict";

  /* 用地范围：比 17 块地各外扩 100 米，留出滨江绿带与外围道路 */
  var BOUNDS = { minX: -3120, maxX: 3260, minZ: -2700, maxZ: 2850 };

  /* 澄川河：西起北岭山脚，东入澄湾，江面宽 190 米，在东段放大成湾。
     [x, 江心 z, 半宽] —— 只允许在两侧片区之间摆动，不能切进任何一块地。 */
  var RIVER = [
    [-3600, 150, 120], [-3120, 142, 112], [-2700, 132, 104], [-2200, 146, 100],
    [-1700, 168, 100], [-1200, 178, 96], [-700, 166, 94], [-200, 184, 96],
    [350, 196, 102], [900, 186, 102], [1450, 174, 106], [1950, 186, 110],
    [2450, 200, 116], [2900, 228, 130], [3300, 246, 146], [3800, 258, 160]
  ];

  /* 跨江桥：x 位置 + 南北桥头 + 桥宽。桥面标高 7 米，两孔拱。 */
  var BRIDGES = [
    { x: 0, z0: 58, z1: 312, w: 36, name: "中枢大桥" },
    { x: -1420, z0: 45, z1: 300, w: 26, name: "西园桥" },
    { x: 1100, z0: 52, z1: 318, w: 26, name: "蜂巢桥" }
  ];

  /* 城际高架：沿北岸的东西向廊道（z≈-1300）穿过全城，两端没入雾里。 */
  var RAIL = {
    y: 22,
    pts: [[-3400, -1200], [-2600, -1210], [-1800, -1196], [-1000, -1206],
      [-200, -1200], [600, -1204], [1400, -1196], [2100, -1208], [2700, -1200], [3400, -1190]],
    stations: [{ x: -1420, name: "西园站" }, { x: 760, name: "云门站" }]
  };

  /* 全城干道：只写长直段，穿过片区的那一截由城市构建器自动剪掉，
     剩下的正好落在片区间隙里；片区内部由各自的街网接手。 */
  var ROADS = [
    /* 三条东西向干道：北廊、南北两岸各一条滨江路、南廊 */
    { a: [-3120, -1300], b: [3260, -1300], w: 30, cls: "avenue" },
    { a: [-3120, -30], b: [3260, -30], w: 26, cls: "avenue" },
    { a: [-3120, 405], b: [3260, 405], w: 24, cls: "avenue" },
    { a: [-3120, 1640], b: [3260, 1640], w: 30, cls: "avenue" },
    /* 南北向：主轴 + 三条次级 */
    { a: [0, -2700], b: [0, 2850], w: 36, cls: "spine" },
    { a: [-1420, -2700], b: [-1420, 2850], w: 28, cls: "avenue" },
    { a: [1100, -2700], b: [1100, 2850], w: 26, cls: "avenue" },
    { a: [2820, -2700], b: [2820, 2850], w: 26, cls: "avenue" },
    /* 片区四周的联络路（由构建器按地块自动生成，这里只声明宽与等级） */
    { ring: true, w: 16, cls: "street" }
  ];

  global.YC_CITY_PLAN = {
    bounds: BOUNDS, river: RIVER, bridges: BRIDGES, rail: RAIL, roads: ROADS,
    /* 江心 z 查询：给树木、绿带、桥头用 */
    riverAt: function (x) {
      for (var i = 1; i < RIVER.length; i++) {
        if (RIVER[i][0] >= x) {
          var a = RIVER[i - 1], b = RIVER[i];
          var t = (x - a[0]) / Math.max(0.001, b[0] - a[0]);
          return { z: a[1] + (b[1] - a[1]) * t, half: a[2] + (b[2] - a[2]) * t };
        }
      }
      var last = RIVER[RIVER.length - 1];
      return { z: last[1], half: last[2] };
    },
    /* 地块矩形（含 34 米路侧带）：城市地面在这里开洞，避免与片区地面共面闪烁 */
    plateRect: function (d, pad) {
      var p = pad || 0;
      return { minX: d.cx - d.hx - p, maxX: d.cx + d.hx + p,
        minZ: d.cz - d.hz - p, maxZ: d.cz + d.hz + p };
    }
  };
})(window);
